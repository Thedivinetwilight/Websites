/**
 * Theru — symbol fallback font.
 *
 * Fraunces and Instrument Sans ship latin subsets only, so glyphs the interface
 * relies on (₹ ⌘ → ← ↵ ≈) fall back to whatever the OS happens to have — and on
 * a bare Linux box that means tofu. This script cuts a ~4 KB WOFF2 containing
 * exactly those glyphs (rupee from Noto Sans Tamil for Indian-script
 * proportions, arrows from DejaVu Sans) and inlines it as a data URI, registered
 * first in the sans stack and behind display faces.
 *
 *   node scripts/build-symbols-font.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, '..')
const SCRATCH = path.join(ROOT, '.scratch/fonts')
fs.mkdirSync(SCRATCH, { recursive: true })

const subset = (src, unicodes, out, extra = []) => {
  execFileSync(
    'python3',
    ['-m', 'fontTools.subset', src, `--unicodes=${unicodes}`, `--output-file=${out}`, '--flavor=woff2', ...extra],
    { stdio: 'inherit' },
  )
  return fs.readFileSync(out).toString('base64')
}

const DEJAVU = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
const NOTO_TAMIL = path.join(ROOT, 'node_modules/@fontsource/noto-sans-tamil/files/noto-sans-tamil-tamil-400-normal.woff2')

const arrows = subset(DEJAVU, 'U+2190,U+2191,U+2192,U+2193,U+21B5,U+2318,U+2248,U+00D7', path.join(SCRATCH, 'arrows.woff2'))
const rupee = subset(NOTO_TAMIL, 'U+20B9', path.join(SCRATCH, 'rupee.woff2'))

const css = `/* Generated by scripts/build-symbols-font.mjs — do not edit by hand. */
@font-face {
  font-family: 'Theru Symbols';
  font-style: normal;
  font-weight: 400 700;
  font-display: swap;
  unicode-range: U+2190-2193, U+21B5, U+2318, U+2248, U+00D7;
  src: url(data:font/woff2;base64,${arrows}) format('woff2');
}

@font-face {
  font-family: 'Theru Rupee';
  font-style: normal;
  font-weight: 400 700;
  font-display: swap;
  unicode-range: U+20B9;
  src: url(data:font/woff2;base64,${rupee}) format('woff2');
}
`

fs.writeFileSync(path.join(ROOT, 'src/styles/symbols.css'), css)
console.log(
  `symbols subset: ${(arrows.length / 1024).toFixed(1)} KB + rupee ${(rupee.length / 1024).toFixed(1)} KB (base64)`,
)
